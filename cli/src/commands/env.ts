/**
 * Service-scoped environment variables ("user data" in the API's vocabulary).
 *
 * Writes trigger a platform process but do NOT restart the service — a running container keeps
 * the old value until it is recreated. `--restart` closes that gap, because "I set the variable
 * and nothing changed" is the most common way this bites.
 */
import { readFile } from "node:fs/promises";
import type { CommandSpec } from "../lib/spec.ts";
import { settleProcess } from "../lib/process.ts";
import { notFound } from "../lib/errors.ts";

interface UserData {
  id: string;
  key: string;
  content: string;
  sensitive?: boolean;
  serviceStackId: string;
}

async function listUserData(ctx: import("../lib/context.ts").Context, serviceId: string): Promise<UserData[]> {
  const res = await ctx.api.call<{ items?: UserData[]; list?: UserData[] }>("ListServiceStackUserData", {
    path: { id: serviceId },
    query: { limit: 1000 },
  });
  return res.items ?? res.list ?? [];
}

const RESTART_FLAG = {
  name: "restart",
  type: "boolean" as const,
  description: "Restart the service afterwards so running containers pick the value up.",
};

async function maybeRestart(
  ctx: import("../lib/context.ts").Context,
  service: { id: string; name: string },
): Promise<unknown> {
  if (!ctx.bool("restart")) {
    ctx.out.info(`note: running containers keep the previous value until ${service.name} is restarted`);
    return null;
  }
  const proc = await ctx.api.call<{ id: string }>("RestartServiceStack", { path: { id: service.id } });
  return settleProcess(ctx, proc, `restarting ${service.name}`);
}

